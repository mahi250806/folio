async function run() {
  await connectDB();
  console.log('Connected. Resetting demo account...');

  const existing = await User.findOne({ email: DEMO.email });
  if (existing) {
    const old = await Paper.find({ userId: existing._id }).select('file').lean();
    for (const p of old) if (p.file?.fileId) await deletePdf(p.file.fileId);
    await Promise.all([
      Paper.deleteMany({ userId: existing._id }),
      Project.deleteMany({ userId: existing._id }),
      Note.deleteMany({ userId: existing._id }),
    ]);
    await existing.deleteOne();
  }

  const user = await User.create({
    name: DEMO.name,
    email: DEMO.email,
    institution: DEMO.institution,
    passwordHash: await bcrypt.hash(DEMO.password, 12),
  });

  const projectIds = {};
  for (const { key, ...p } of PROJECTS) {
    const doc = await Project.create({ ...p, userId: user._id });
    projectIds[key] = doc._id;
  }

  let pdfs = 0;
  for (const [i, p] of PAPERS.entries()) {
    const { projects, finished, readBy, pdf, ...fields } = p;
    const paper = new Paper({
      ...fields,
      userId: user._id,
      paperType: fields.paperType || 'Journal article',
      url: `https://doi.org/${fields.doi}`,
      projectIds: projects.map((k) => projectIds[k]),
      readBy: readBy !== undefined ? days(readBy) : undefined,
      finishedAt: finished !== undefined ? days(finished) : undefined,
    });
    // Stagger "added" dates so the list has a realistic order.
    paper.$locals.createdAt = days(-(PAPERS.length - i) * 4);
    if (pdf) {
      const fileName = `${fields.authors[0].split(' ').pop()}-${fields.year}.pdf`;
      paper.file = await savePdf(makePdf(fields.title, fields.authors.join(', ')), { userId: user._id, originalName: fileName });
      pdfs += 1;
    }
    await paper.save();
    await Paper.collection.updateOne({ _id: paper._id }, { $set: { createdAt: paper.$locals.createdAt } });

    const prefix = Object.keys(NOTES).find((k) => fields.title.startsWith(k));
    if (prefix) {
      await Note.insertMany(
        NOTES[prefix].map(([kind, content, page]) => ({ userId: user._id, paperId: paper._id, kind, content, page: page ?? undefined }))
      );
    }
  }

  const noteCount = await Note.countDocuments({ userId: user._id });
  console.log(`Seeded ${PROJECTS.length} projects, ${PAPERS.length} papers (${pdfs} with PDFs), ${noteCount} notes.`);
  console.log(`Log in with ${DEMO.email} / ${DEMO.password}`);
  await mongoose.disconnect();
}

run().catch(async (err) => {
  console.error('Seed failed:', err.message);
  await mongoose.disconnect();
  process.exit(1);
});
