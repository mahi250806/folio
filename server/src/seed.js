/** Builds a small, valid one-page PDF with the paper's title, so uploads can be previewed. */
function makePdf(title, authors) {
  const esc = (s) => s.replace(/[\\()]/g, '\\$&').replace(/[^\x20-\x7E]/g, '');
  const lines = [
    `BT /F1 18 Tf 72 720 Td (${esc(title.slice(0, 60))}) Tj ET`,
    `BT /F1 12 Tf 72 690 Td (${esc(authors.slice(0, 80))}) Tj ET`,
    'BT /F1 10 Tf 72 660 Td (Sample PDF generated by the FOLIO seed script.) Tj ET',
  ].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(lines)} >>\nstream\n${lines}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Times-Roman >>',
  ];
  let out = '%PDF-1.4\n';
  const offsets = [];
  objects.forEach((o, i) => {
    offsets.push(Buffer.byteLength(out));
    out += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((n) => `${String(n).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

